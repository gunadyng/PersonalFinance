// Supabase settings come from (first non-blank wins): environment variables,
// local.properties, then gradle.properties. The anon key is public by design; Row Level Security
// in the database keeps each user's rows private.
val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun setting(name: String): String =
    listOf(System.getenv(name), localProps.getProperty(name), findProperty(name) as String?)
        .firstOrNull { !it.isNullOrBlank() }.orEmpty()

